def ensure_dirs() -> None:
    ASSETS_DIR.mkdir(parents=True, exist_ok=True)
    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    CACHE_DIR.mkdir(parents=True, exist_ok=True)


def download_natural_earth() -> None:
    """Download and extract Natural Earth Admin 0 1:10m once."""
    if NE_SHP.exists():
        print(f"Natural Earth cache found:\n  {NE_SHP}")
        return

    print("\nDownloading Natural Earth Admin 0 1:10m...")
    CACHE_DIR.mkdir(parents=True, exist_ok=True)

    try:
        urllib.request.urlretrieve(NATURAL_EARTH_URL, NE_ZIP)
    except Exception as exc:
        raise RuntimeError(
            "Could not download Natural Earth.\n"
            f"URL: {NATURAL_EARTH_URL}\n"
            "Check your internet connection and run the script again."
        ) from exc

    NE_DIR.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(NE_ZIP, "r") as zf:
        zf.extractall(NE_DIR)

    if not NE_SHP.exists():
        raise FileNotFoundError(
            "Natural Earth was downloaded but the expected shapefile "
            f"was not found:\n{NE_SHP}"
        )

    print(f"Natural Earth extracted to:\n  {NE_DIR}")


def repair_geometry(gdf: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    """Remove empty geometries and repair invalid ones."""
    gdf = gdf.copy()

    gdf = gdf[gdf.geometry.notna()].copy()
    gdf = gdf[~gdf.geometry.is_empty].copy()

    invalid = ~gdf.geometry.is_valid

    if invalid.any():
        print(f"Repairing {int(invalid.sum()):,} invalid geometries...")

        if make_valid is not None:
            gdf.loc[invalid, "geometry"] = (
                gdf.loc[invalid, "geometry"].apply(make_valid)
            )
        else:
            gdf.loc[invalid, "geometry"] = (
                gdf.loc[invalid, "geometry"].buffer(0)
            )

    gdf = gdf[gdf.geometry.notna()].copy()
    gdf = gdf[~gdf.geometry.is_empty].copy()

    return gdf


def derive_country_code(region_id: str) -> str:
    """
    P1 region_id examples:
      BRA__BRA_2015_GAUL1_670
      USA__USA_2015_GAUL1_3251

    The first token is the ISO3 country code used by the project.
    """
    value = str(region_id).strip()

    if "__" not in value:
        raise ValueError(
            f"Cannot derive country code from region_id: {region_id!r}"
        )

    code = value.split("__", 1)[0].strip().upper()

    if len(code) != 3:
        raise ValueError(
            f"Derived invalid country code {code!r} "
            f"from region_id {region_id!r}"
        )

    return code


def read_analytical_regions() -> gpd.GeoDataFrame:
    """Read the analytical 512-region TopoJSON."""
    if not ANALYTICAL_SOURCE.exists():
        raise FileNotFoundError(
            "\nAnalytical source map not found.\n\n"
            f"Expected:\n  {ANALYTICAL_SOURCE}\n\n"
            "Place the original 512-region TopoJSON in that location and "
            "rename it to:\n"
            "  P1_ADM1_regions_analytical.topojson\n"
        )

    print("\nReading analytical ADM1 source...")
    analytical = gpd.read_file(ANALYTICAL_SOURCE)

    if REGION_KEY not in analytical.columns:
        raise KeyError(
            f"The analytical map must contain the key '{REGION_KEY}'.\n"
            f"Columns found: {list(analytical.columns)}"
        )

    if analytical.crs is None:
        raise ValueError(
            "The analytical map has no CRS. "
            "It must be defined before generating the Power BI map."
        )

    analytical = analytical.to_crs("EPSG:4326")
    analytical = repair_geometry(analytical)

    analytical[REGION_KEY] = (
        analytical[REGION_KEY]
        .astype(str)
        .str.strip()
    )

    if analytical[REGION_KEY].duplicated().any():
        duplicated = (
            analytical.loc[
                analytical[REGION_KEY].duplicated(keep=False),
                REGION_KEY,
            ]
            .drop_duplicates()
            .tolist()
        )

        raise ValueError(
            "Duplicated analytical region_id values found:\n"
            + "\n".join(map(str, duplicated[:30]))
        )

    if len(analytical) != EXPECTED_ANALYTICAL_REGIONS:
        raise ValueError(
            f"Expected {EXPECTED_ANALYTICAL_REGIONS} analytical regions, "
            f"but found {len(analytical)}."
        )

    analytical["country_code"] = analytical[REGION_KEY].map(
        derive_country_code
    )

    analytical["map_role"] = "analytical"

    if ANALYTICAL_SIMPLIFY_TOLERANCE > 0:
        analytical["geometry"] = analytical.geometry.simplify(
            ANALYTICAL_SIMPLIFY_TOLERANCE,
            preserve_topology=True,
        )

    keep = [
        REGION_KEY,
        "country_code",
        "map_role",
        "geometry",
    ]

    return analytical[keep].copy()


def choose_world_iso3_column(world: gpd.GeoDataFrame) -> str:
    """
    Natural Earth has several ISO-like columns.
    ADM0_A3 is preferred because it is populated for territories where ISO_A3
    can contain '-99'.
    """
    candidates = [
        "ADM0_A3",
        "ISO_A3_EH",
        "ISO_A3",
        "SOV_A3",
    ]

    for column in candidates:
        if column in world.columns:
            return column

    raise KeyError(
        "Could not find a usable ISO3 column in Natural Earth.\n"
        f"Columns found: {list(world.columns)}"
    )


def read_world() -> tuple[gpd.GeoDataFrame, str]:
    """Read Natural Earth world polygons."""
    download_natural_earth()

    print("\nReading Natural Earth world layer...")
    world = gpd.read_file(NE_SHP)

    if world.crs is None:
        raise ValueError("Natural Earth layer has no CRS.")

    world = world.to_crs("EPSG:4326")
    world = repair_geometry(world)

    iso_col = choose_world_iso3_column(world)

    world[iso_col] = (
        world[iso_col]
        .astype(str)
        .str.strip()
        .str.upper()
    )

    world = world[
        ~world[iso_col].isin(EXCLUDED_WORLD_ISO3)
    ].copy()

    # Remove empty/placeholder ISO entries only when there is no meaningful
    # country/territory identifier.
    world = world[
        world[iso_col].notna()
        & (world[iso_col] != "")
    ].copy()

    return world, iso_col


def build_world_background(
    world: gpd.GeoDataFrame,
    world_iso_col: str,
    analytical: gpd.GeoDataFrame,
) -> gpd.GeoDataFrame:
    """
    Build the grey world layer.

    Critical rule:
    - A country is NEVER removed just because it belongs to the P1 sample.
    - For a study country, only the portions already covered by analytical
      regions are subtracted.
    - Any uncovered national territory remains grey.
    """
    print("\nBuilding precise grey world background...")

    study_countries = set(
        analytical["country_code"]
        .dropna()
        .astype(str)
        .str.upper()
    )

    background_rows: list[dict] = []

    for idx, country in world.iterrows():
        iso3 = str(country[world_iso_col]).strip().upper()
        country_geom = country.geometry

        if country_geom is None or country_geom.is_empty:
            continue

        # Countries outside the study: keep the full country.
        if iso3 not in study_countries:
            background_rows.append(
                {
                    REGION_KEY: f"BG_{iso3}_{idx}",
                    "country_code": iso3,
                    "map_role": "background",
                    "geometry": country_geom,
                }
            )
            continue

        # Countries inside the study:
        # subtract only the analytical polygons that belong to that country.
        country_regions = analytical.loc[
            analytical["country_code"] == iso3,
            "geometry",
        ]

        valid_parts = [
            geom
            for geom in country_regions
            if geom is not None and not geom.is_empty
        ]

        # Defensive fallback:
        # if country-code matching fails, keep the country grey instead of
        # allowing it to disappear.
        if not valid_parts:
            background_rows.append(
                {
                    REGION_KEY: f"BG_{iso3}_{idx}",
                    "country_code": iso3,
                    "map_role": "background",
                    "geometry": country_geom,
                }
            )
            continue

        analytical_union = unary_union(valid_parts)

        try:
            residual = country_geom.difference(analytical_union)
        except Exception:
            country_geom = (
                make_valid(country_geom)
                if make_valid is not None
                else country_geom.buffer(0)
            )
            analytical_union = (
                make_valid(analytical_union)
                if make_valid is not None
                else analytical_union.buffer(0)
            )
            residual = country_geom.difference(analytical_union)

        if residual is not None and not residual.is_empty:
            background_rows.append(
                {
                    REGION_KEY: f"BG_{iso3}_{idx}",
                    "country_code": iso3,
                    "map_role": "background",
                    "geometry": residual,
                }
            )

    background = gpd.GeoDataFrame(
        background_rows,
        geometry="geometry",
        crs="EPSG:4326",
    )

    background = repair_geometry(background)

    if BACKGROUND_SIMPLIFY_TOLERANCE > 0:
        background["geometry"] = background.geometry.simplify(
            BACKGROUND_SIMPLIFY_TOLERANCE,
            preserve_topology=True,
        )
        background = repair_geometry(background)

    return background


def combine_layers(
    background: gpd.GeoDataFrame,
    analytical: gpd.GeoDataFrame,
) -> gpd.GeoDataFrame:
    """
    Background comes first and analytical polygons second so the analytical
    layer remains the foreground in renderers that respect feature order.
    """
    print("\nCombining background + analytical regions...")

    final = pd.concat(
        [background, analytical],
        ignore_index=True,
    )

    final = gpd.GeoDataFrame(
        final,
        geometry="geometry",
        crs="EPSG:4326",
    )

    final = repair_geometry(final)

    # Unique map keys are mandatory.
    if final[REGION_KEY].duplicated().any():
        duplicated = (
            final.loc[
                final[REGION_KEY].duplicated(keep=False),
                REGION_KEY,
            ]
            .drop_duplicates()
            .tolist()
        )

        raise ValueError(
            "Duplicated final map keys found:\n"
            + "\n".join(map(str, duplicated[:30]))
        )

    return final


def validate_world_map(
    world: gpd.GeoDataFrame,
    world_iso_col: str,
    analytical: gpd.GeoDataFrame,
    background: gpd.GeoDataFrame,
    final: gpd.GeoDataFrame,
) -> None:
    """Hard QA before export."""
    print("\n" + "=" * 72)
    print("WORLD MAP QA")
    print("=" * 72)

    analytical_ids = analytical[REGION_KEY].nunique()
    analytical_countries = analytical["country_code"].nunique()
    world_codes = set(world[world_iso_col].astype(str).str.upper())

    print(f"Analytical regions      : {analytical_ids:,}")
    print(f"Analytical countries    : {analytical_countries:,}")
    print(f"World source features   : {len(world):,}")
    print(f"Background geometries   : {len(background):,}")
    print(f"Final geometries        : {len(final):,}")

    if analytical_ids != EXPECTED_ANALYTICAL_REGIONS:
        raise AssertionError(
            f"Expected {EXPECTED_ANALYTICAL_REGIONS} analytical regions."
        )

    if len(analytical) != EXPECTED_ANALYTICAL_REGIONS:
        raise AssertionError(
            "Analytical feature count changed unexpectedly."
        )

    if final.geometry.isna().any():
        raise AssertionError("Final map contains null geometries.")

    if final.geometry.is_empty.any():
        raise AssertionError("Final map contains empty geometries.")

    # Countries explicitly checked because they are visually important for
    # world completeness and were involved in previous rendering issues.
    important_world_codes = {"CAN", "USA", "RUS", "BRA", "AUS", "CHN", "IND"}

    missing_world = sorted(
        important_world_codes - world_codes
    )

    if missing_world:
        raise AssertionError(
            "Natural Earth world layer is unexpectedly missing: "
            + ", ".join(missing_world)
        )

    # Canada must exist somewhere in the final map:
    # either as analytical territory or as grey background.
    canada_present = (
        (final["country_code"] == "CAN").any()
    )

    if not canada_present:
        raise AssertionError(
            "Canada disappeared from the final map."
        )

    # Same defensive checks for other large world extents.
    for code in ["USA", "RUS", "AUS"]:
        if not (final["country_code"] == code).any():
            raise AssertionError(
                f"{code} disappeared from the final map."
            )

    print("WORLD MAP QA: PASSED")


def export_geojson(final: gpd.GeoDataFrame) -> None:
    """Optional audit/debug output."""
    print("\nExporting GeoJSON audit copy...")
    final.to_file(
        FINAL_GEOJSON,
        driver="GeoJSON",
    )
    print(f"  {FINAL_GEOJSON}")


def expand_topojson_bbox(
    topology_dict: dict,
    fraction: float,
) -> dict:
    """
    Expand the horizontal bbox without changing polygon coordinates.

    Some renderers use bbox to determine initial fit. If the renderer ignores
    bbox, the geometry remains valid and unchanged.
    """
    bbox = topology_dict.get("bbox")

    if (
        bbox
        and isinstance(bbox, list)
        and len(bbox) == 4
        and fraction > 0
    ):
        min_x, min_y, max_x, max_y = map(float, bbox)

        width = max_x - min_x
        pad = width * fraction

        topology_dict["bbox"] = [
            min_x - pad,
            min_y,
            max_x + pad,
            max_y,
        ]

    return topology_dict


def export_topojson(final: gpd.GeoDataFrame) -> None:
    """Create the Power BI custom map."""
    if Topology is None:
        raise ImportError(
            "Package 'topojson' is not installed.\n\n"
            "Activate the P1 .venv and run:\n"
            "  pip install topojson"
        )

    print("\nBuilding TopoJSON...")

    topology = Topology(
        final,
        prequantize=True,
    )

    topology_dict = json.loads(
        topology.to_json()
    )

    topology_dict = expand_topojson_bbox(
        topology_dict,
        HORIZONTAL_BBOX_PADDING_FRACTION,
    )

    # Validate serialization before writing.
    text = json.dumps(
        topology_dict,
        ensure_ascii=False,
        separators=(",", ":"),
    )

    json.loads(text)

    FINAL_TOPOJSON.write_text(
        text,
        encoding="utf-8",
    )

    print(f"  {FINAL_TOPOJSON}")


def export_audit(
    analytical: gpd.GeoDataFrame,
    background: gpd.GeoDataFrame,
    final: gpd.GeoDataFrame,
) -> None:
    """Write a compact audit table for reproducibility."""
    audit = pd.DataFrame(
        {
            "metric": [
                "analytical_regions",
                "analytical_countries",
                "background_geometries",
                "final_geometries",
                "canada_present",
                "usa_present",
                "russia_present",
                "australia_present",
            ],
            "value": [
                len(analytical),
                analytical["country_code"].nunique(),
                len(background),
                len(final),
                bool((final["country_code"] == "CAN").any()),
                bool((final["country_code"] == "USA").any()),
                bool((final["country_code"] == "RUS").any()),
                bool((final["country_code"] == "AUS").any()),
            ],
        }
    )

    audit.to_csv(
        AUDIT_CSV,
        index=False,
        encoding="utf-8-sig",
    )

    print(f"\nAudit CSV:\n  {AUDIT_CSV}")


def main() -> None:
    print("=" * 72)
    print("P1 — POWER BI WORLD + ADM1 MAP BUILDER")
    print("=" * 72)

    ensure_dirs()

    analytical = read_analytical_regions()
    world, world_iso_col = read_world()

    background = build_world_background(
        world=world,
        world_iso_col=world_iso_col,
        analytical=analytical,
    )

    final = combine_layers(
        background=background,
        analytical=analytical,
    )

    validate_world_map(
        world=world,
        world_iso_col=world_iso_col,
        analytical=analytical,
        background=background,
        final=final,
    )

    export_geojson(final)
    export_topojson(final)
    export_audit(
        analytical=analytical,
        background=background,
        final=final,
    )

    print("\n" + "=" * 72)
    print("MAP BUILD COMPLETE")
    print("=" * 72)

    print(
        f"""
Input analytical map:
  {ANALYTICAL_SOURCE}

Power BI TopoJSON:
  {FINAL_TOPOJSON}

GeoJSON audit copy:
  {FINAL_GEOJSON}

Expected Power BI join key:
  {REGION_KEY}

Important:
  - C1 / C2 / Transition colours continue to come from Power BI.
  - Grey areas are background/no-data territory.
  - Transition remains a display flag, not a third analytical cluster.
"""
    )


if __name__ == "__main__":
    try:
        main()

    except Exception as exc:
        print("\n" + "=" * 72)
        print("ERROR")
        print("=" * 72)
        print(exc)
        sys.exit(1)
